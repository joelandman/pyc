    void emit_range_next(const ir::Instr& in) {
        std::string p = "%rg" + std::to_string((int)in.imm);
        std::string c = fresh(), st = fresh();
        std::string pos = fresh();
        std::string posc = "rpos" + std::to_string(tmp_++);
        std::string negc = "rneg" + std::to_string(tmp_++);
        std::string take = "rtake" + std::to_string(tmp_++);
        const bool ssa_cur = in.args.size() >= 2 && in.args[1].valid();
        if (ssa_cur)
            c = v(in.args[1]);
        else
            o_ << "  " << c << " = load i64, ptr " << p << ".i\n";
        const bool ssa_stop = in.args.size() >= 1 && in.args[0].valid();
        std::string e = ssa_stop ? v(in.args[0]) : fresh();
        if (!ssa_stop)
            o_ << "  " << e << " = load i64, ptr " << p << ".e\n";
        if (in.text == "1") {
            need("declare i1 @llvm.expect.i1(i1, i1)");
            std::string ge = fresh(), gexp = fresh();
            o_ << "  " << ge << " = icmp sge i64 " << c << ", " << e << "\n";
            o_ << "  " << gexp << " = call i1 @llvm.expect.i1(i1 " << ge
               << ", i1 false)\n";
            o_ << "  br i1 " << gexp << ", label %bb" << in.target_else
               << ", label %" << take << "\n";
            o_ << take << ":\n";
            o_ << "  " << v(*in.result) << " = add i64 " << c << ", 0\n";
            std::string nv = fresh();
            o_ << "  " << nv << " = add nsw i64 " << c << ", 1\n";
            o_ << "  store i64 " << nv << ", ptr " << p << ".i\n";
            o_ << "  br label %bb" << in.target << "\n";
            return;
        }
        o_ << "  " << st << " = load i64, ptr " << p << ".p\n";
        o_ << "  " << pos << " = icmp sgt i64 " << st << ", 0\n";
        o_ << "  br i1 " << pos << ", label %" << posc << ", label %" << negc << "\n";
        need("declare i1 @llvm.expect.i1(i1, i1)");
        o_ << posc << ":\n";
        std::string ge = fresh(), gexp = fresh();
        o_ << "  " << ge << " = icmp sge i64 " << c << ", " << e << "\n";
        o_ << "  " << gexp << " = call i1 @llvm.expect.i1(i1 " << ge
           << ", i1 false)\n";
        o_ << "  br i1 " << gexp << ", label %bb" << in.target_else
           << ", label %" << take << "\n";
        o_ << negc << ":\n";
        std::string le = fresh(), lexp = fresh();
        o_ << "  " << le << " = icmp sle i64 " << c << ", " << e << "\n";
        o_ << "  " << lexp << " = call i1 @llvm.expect.i1(i1 " << le
           << ", i1 false)\n";
        o_ << "  br i1 " << lexp << ", label %bb" << in.target_else
           << ", label %" << take << "\n";
        o_ << take << ":\n";
        o_ << "  " << v(*in.result) << " = add i64 " << c << ", 0\n";
        need("declare {i64, i1} @llvm.sadd.with.overflow.i64(i64, i64)");
        std::string agg = fresh(), nv = fresh(), ov = fresh(), nxt = fresh();
        o_ << "  " << agg << " = call {i64, i1} @llvm.sadd.with.overflow.i64(i64 "
           << c << ", i64 " << st << ")\n";
        o_ << "  " << nv << " = extractvalue {i64, i1} " << agg << ", 0\n";
        o_ << "  " << ov << " = extractvalue {i64, i1} " << agg << ", 1\n";
        o_ << "  " << nxt << " = select i1 " << ov << ", i64 " << e << ", i64 "
           << nv << "\n";
        o_ << "  store i64 " << nxt << ", ptr " << p << ".i\n";
        o_ << "  br label %bb" << in.target << "\n";
    }

    void emit_capi(const ir::Instr& in) {
        bool ptr_ret = (in.result_ownership == Ownership::Owned
                     || in.result_ownership == Ownership::Borrowed
                     || in.result_ownership == Ownership::AlwaysNull);
        const rt::CApiSymbol* sym = rt::lookup(in.text);
        std::string kinds = sym ? std::string(sym->param_kinds) : std::string();
        std::ostringstream sig, call;
        sig << "declare " << (ptr_ret ? "ptr" : "i32") << " @" << in.text << "(";
        call << "  " << v(*in.result) << " = call " << (ptr_ret ? "ptr" : "i32")
             << " @" << in.text << "(";
        // The immediate occupies its true C parameter position, which is what
        // makes the steal indices in §4's table line up with reality.
        std::size_t ai = 0;
        std::size_t total = in.args.size() + (in.has_imm ? 1 : 0);
        for (std::size_t p = 0; p < total; ++p) {
            if (p) { sig << ", "; call << ", "; }
            char k = (p < kinds.size()) ? kinds[p] : 'o';
            if (in.has_imm && (int)p == imm_pos(in, total)) {
                sig << "i64"; call << "i64 " << in.imm;
            } else if (k == 'i') {
                // The IR value is a machine int (i32); widen it to the
                // parameter's width rather than passing a pointer.
                std::string w = fresh();
                pre_ << "  " << w << " = zext i32 " << v(in.args[ai++]) << " to i64\n";
                sig << "i64"; call << "i64 " << w;
            } else {
                sig << "ptr"; call << "ptr " << v(in.args[ai++]);
            }
        }
        sig << ")"; call << ")\n";
        need(sig.str());
        o_ << pre_.str();
        pre_.str("");
        o_ << call.str();
        check(in, v(*in.result), ptr_ret);
    }

    // Lowering does not record imm_pos in the instruction, so recover it:
    // a size argument leads (PyList_New), an index sits at parameter 1
    // (PyList_SetItem), and a compare opid trails (PyObject_RichCompare).
    static int imm_pos(const ir::Instr& in, std::size_t total) {
        if (in.args.empty()) return 0;
        if (in.text == "PyObject_RichCompare") return (int)total - 1;
        return 1;
    }

    // Every alloca goes in the ENTRY block, never where it is used.
    //
    // An alloca inside a loop body is not reclaimed until the function
    // returns, so each iteration took another slice of C stack. Measured: any
    // call in a loop -- `len(b"abc")`, anything -- died with
    //
    //     RecursionError: Stack overflow (used 8148 kB) while calling a
    //     Python object
    //
    // after roughly 500,000 iterations, about 16 bytes a call. A loop with no
    // call in it (`c += 1`) ran forever, which is what localised it to the
    // call's argument array rather than to loops in general. Any long-running
    // compiled program that calls anything in a loop would eventually die.
    //
    // Collected during the discarded first emission pass and written out
    // before bb0 in the second. The passes restore tmp_ between them, so the
    // names they generate are identical and the recorded ones match.
    std::string hoisted_alloca(std::size_t n) {
        std::string name = fresh();
        allocas_.push_back({name, n});
        return name;
    }
    std::vector<std::pair<std::string, std::size_t>> allocas_;
    // LookupMethod result id -> hoisted `[1 x ptr]` that holds the borrowed
    // self (or null). Filled while emitting the lookup, read by the call.
    std::map<std::uint32_t, std::string> method_slot_;

    std::string method_self_elem(std::uint32_t callable) {
        auto it = method_slot_.find(callable);
        if (it == method_slot_.end()) return {};
        std::string p = fresh();
        o_ << "  " << p << " = getelementptr [1 x ptr], ptr " << it->second
           << ", i64 0, i64 0\n";
        return p;
    }

    void emit_lookup_method(const ir::Instr& in) {
        need("declare ptr @pyc_rt_lookup_method(ptr, ptr, ptr)");
        std::string arr = hoisted_alloca(1);
        method_slot_[in.result->id] = arr;
        std::string p = fresh();
        o_ << "  " << p << " = getelementptr [1 x ptr], ptr " << arr
           << ", i64 0, i64 0\n";
        o_ << "  store ptr null, ptr " << p << "\n";
        o_ << "  " << v(*in.result) << " = call ptr @pyc_rt_lookup_method(ptr "
           << v(in.args[0]) << ", ptr " << v(in.args[1]) << ", ptr " << p
           << ")\n";
        check(in, v(*in.result), true);
    }

    void emit_call(const ir::Instr& in) {
        // "meth" / "methkw:" is a call whose callee was LookupMethod. The
        // self slot is null when the attribute was not an unbound method.
        bool method = false;
        std::string text = in.text;
        if (text == "meth") {
            method = true;
            text.clear();
        } else if (text.compare(0, 7, "methkw:") == 0) {
            method = true;
            text = "kw:" + text.substr(7);
        }
        if (text.size() > 3 && text.compare(0, 3, "kw:") == 0) {
            need("declare ptr @pyc_rt_call_kw(ptr, ptr, i64, ptr)");
            std::string csv = text.substr(3);
            int slot = intern_kw(csv);
            std::size_t nkw = 1;
            for (char ch : csv) if (ch == ',') nkw++;
            std::size_t n = in.args.size() - 1;
            std::size_t npos = n - nkw;
            std::string arr = hoisted_alloca(n ? n : 1);
            for (std::size_t i = 0; i < n; ++i) {
                std::string p = fresh();
                o_ << "  " << p << " = getelementptr [" << (n ? n : 1)
                   << " x ptr], ptr " << arr << ", i64 0, i64 " << i << "\n";
                o_ << "  store ptr " << v(in.args[i + 1]) << ", ptr " << p << "\n";
            }
            std::string kp = fresh(), kn = fresh();
            o_ << "  " << kp << " = getelementptr inbounds ptr, ptr @.kwnames, i64 "
               << slot << "\n";
            o_ << "  " << kn << " = load ptr, ptr " << kp << "\n";
            if (method) {
                need("declare ptr @pyc_rt_call_bound_kw(ptr, ptr, ptr, i64, ptr)");
                std::string selfp = method_self_elem(in.args[0].id);
                std::string self = fresh();
                o_ << "  " << self << " = load ptr, ptr " << selfp << "\n";
                o_ << "  " << v(*in.result)
                   << " = call ptr @pyc_rt_call_bound_kw(ptr "
                   << v(in.args[0]) << ", ptr " << self << ", ptr " << arr
                   << ", i64 " << npos << ", ptr " << kn << ")\n";
            } else {
                o_ << "  " << v(*in.result) << " = call ptr @pyc_rt_call_kw(ptr "
                   << v(in.args[0]) << ", ptr " << arr << ", i64 " << npos
                   << ", ptr " << kn << ")\n";
            }
            check(in, v(*in.result), true);
            return;
        }
        // A CallObject carries the callable in args[0]. (The former "m"
        // VectorcallMethod form was removed: it deferred the attribute lookup
        // past the argument evaluation, a silent wrong answer -- see
        // verify/corpus/language/deco_eval_order.py.) "meth" looks the name
        // up first (LookupMethod) and prepends self only when that lookup
        // returned an unbound descriptor.
        std::size_t n = in.args.size() - 1;
        std::string arr = hoisted_alloca(n ? n : 1);
        for (std::size_t i = 0; i < n; ++i) {
            std::string p = fresh();
            o_ << "  " << p << " = getelementptr [" << (n ? n : 1)
               << " x ptr], ptr " << arr << ", i64 0, i64 " << i << "\n";
            o_ << "  store ptr " << v(in.args[i + 1]) << ", ptr " << p << "\n";
        }
        if (method) {
            need("declare ptr @pyc_rt_call_bound(ptr, ptr, ptr, i64)");
            std::string selfp = method_self_elem(in.args[0].id);
            std::string self = fresh();
            o_ << "  " << self << " = load ptr, ptr " << selfp << "\n";
            o_ << "  " << v(*in.result) << " = call ptr @pyc_rt_call_bound(ptr "
               << v(in.args[0]) << ", ptr " << self << ", ptr " << arr
               << ", i64 " << n << ")\n";
        } else {
            need("declare ptr @pyc_rt_call(ptr, ptr, i64)");
            o_ << "  " << v(*in.result) << " = call ptr @pyc_rt_call(ptr "
               << v(in.args[0]) << ", ptr " << arr << ", i64 " << n << ")\n";
        }
        check(in, v(*in.result), true);
    }

    // Build the closure tuple inline: a small alloca holding the cells this
    // nested function captures, in freevar order.
    // args[0] = defaults, args[1] = kwdefaults, args[2..] = closure cells.
    std::string closure_arg(const ir::Instr& in) {
        std::size_t n = in.args.size() > 2 ? in.args.size() - 2 : 0;
        if (!n) return "null";
        std::string arr = hoisted_alloca(n);
        for (std::size_t i = 0; i < n; ++i) {
            std::string p = fresh();
            pre_ << "  " << p << " = getelementptr [" << n << " x ptr], ptr "
                 << arr << ", i64 0, i64 " << i << "\n";
            pre_ << "  store ptr " << v(in.args[i + 2]) << ", ptr " << p << "\n";
        }
        return arr;
    }

    std::map<std::string, std::string> argnames_;
    std::string argnames_global(std::size_t idx) {
        const ir::Function& f = m_.functions[idx];
        const auto& names = f.locals.empty() ? f.params : f.locals;
        if (names.empty()) return "null";
        auto it = argnames_.find(std::to_string(idx));
        if (it != argnames_.end()) return it->second;
        std::string g = "@.args" + std::to_string(idx);
        std::string body = "[" + std::to_string(names.size()) + " x ptr] [";
        for (std::size_t i = 0; i < names.size(); ++i)
            body += (i ? ", ptr " : "ptr ") + cstr(names[i]);
        body += "]";
        argnames_[std::to_string(idx)] = g;
        argname_defs_.push_back(g + " = private unnamed_addr constant " + body);
        return g;
    }
    std::string loc_global(std::size_t idx) {
        if (idx >= fn_locs_.size() || fn_locs_[idx].empty()) return "null";
        return "@.locs" + std::to_string(idx);
    }
    std::string jtl_global(std::size_t idx) {
        if (idx >= fn_jtl_.size() || fn_jtl_[idx].empty()) return "null";
        return "@.jtl" + std::to_string(idx);
    }
    std::vector<std::string> argname_defs_;
    std::vector<std::string> genexp_caches_;
    int genexp_n_ = 0;
    int tb_n_ = 0;

    void emit_constants() {
        for (const std::string& d : genexp_caches_) o_ << d << "\n";
        for (const std::string& d : argname_defs_) o_ << d << "\n";
        for (std::size_t i = 0; i < fn_locs_.size(); ++i) {
            const auto& v = fn_locs_[i];
            if (v.empty()) continue;
            o_ << "@.locs" << i << " = private unnamed_addr constant ["
               << v.size() << " x i32] [";
            for (std::size_t j = 0; j < v.size(); ++j)
                o_ << (j ? ", i32 " : "i32 ") << v[j];
            o_ << "]\n";
        }
        for (std::size_t i = 0; i < fn_jtl_.size(); ++i) {
            const auto& v = fn_jtl_[i];
            if (v.empty()) continue;
            o_ << "@.jtl" << i << " = private unnamed_addr constant ["
               << v.size() << " x i32] [";
            for (std::size_t j = 0; j < v.size(); ++j)
                o_ << (j ? ", i32 " : "i32 ") << v[j];
            o_ << "]\n";
        }
        o_ << "\n";
        for (const auto& [text, name] : strs_)
            o_ << name << " = private unnamed_addr constant ["
               << text.size() + 1 << " x i8] c\"" << escape(text) << "\\00\"\n";
    }
    // The table, and the function that fills it. Emitted after every body so
    // the size is known; LLVM does not require a global to be defined before
    // its uses.
    void emit_pyconsts() {
        std::size_t n = pyconst_order_.size() ? pyconst_order_.size() : 1;
        std::size_t nn = pyname_order_.size() ? pyname_order_.size() : 1;
        std::size_t nk = kw_order_.size() ? kw_order_.size() : 1;
        o_ << "\n@.pyconsts = internal global [" << n
           << " x ptr] zeroinitializer\n";
        o_ << "@.pycnames = internal global [" << nn
           << " x ptr] zeroinitializer\n";
        o_ << "@.kwnames = internal global [" << nk
           << " x ptr] zeroinitializer\n\n";
        o_ << "define internal i32 @__pyc_init_consts() {\nentry:\n";
        for (std::size_t i = 0; i < pyconst_order_.size(); ++i) {
            const char kind = pyconst_order_[i].first;
            const std::string& text = pyconst_order_[i].second;
            std::string val = "%c" + std::to_string(i);
            std::string ptr = "%p" + std::to_string(i);
            std::string ok = "ok" + std::to_string(i);
            switch (kind) {
                case 's':
                    need("declare ptr @pyc_rt_str(ptr, i64)");
                    o_ << "  " << val << " = call ptr @pyc_rt_str(ptr " << cstr(text)
                       << ", i64 " << text.size() << ")\n";
                    break;
                case 'b':
                    need("declare ptr @pyc_rt_bytes(ptr, i64)");
                    o_ << "  " << val << " = call ptr @pyc_rt_bytes(ptr " << cstr(text)
                       << ", i64 " << text.size() << ")\n";
                    break;
                case 'i':
                    need("declare ptr @pyc_rt_int_from_text(ptr)");
                    o_ << "  " << val << " = call ptr @pyc_rt_int_from_text(ptr "
                       << cstr(text) << ")\n";
                    break;
                default:
                    need("declare ptr @PyFloat_FromDouble(double)");
                    o_ << "  " << val << " = call ptr @PyFloat_FromDouble(double "
                       << fp(text) << ")\n";
                    break;
            }
            std::string isnull = "%n" + std::to_string(i);
            o_ << "  " << isnull << " = icmp eq ptr " << val << ", null\n";
            o_ << "  br i1 " << isnull << ", label %fail, label %" << ok << "\n";
            o_ << ok << ":\n";
            o_ << "  " << ptr << " = getelementptr inbounds ptr, ptr "
               << "@.pyconsts, i64 " << i << "\n";
            o_ << "  store ptr " << val << ", ptr " << ptr << "\n";
        }
        for (std::size_t i = 0; i < pyname_order_.size(); ++i) {
            const std::string& text = pyname_order_[i];
            need("declare ptr @pyc_rt_intern(ptr)");
            std::string val = "%g" + std::to_string(i);
            std::string ptr = "%q" + std::to_string(i);
            std::string ok = "gok" + std::to_string(i);
            std::string isnull = "%m" + std::to_string(i);
            o_ << "  " << val << " = call ptr @pyc_rt_intern(ptr " << cstr(text) << ")\n";
            o_ << "  " << isnull << " = icmp eq ptr " << val << ", null\n";
            o_ << "  br i1 " << isnull << ", label %fail, label %" << ok << "\n";
            o_ << ok << ":\n";
            o_ << "  " << ptr << " = getelementptr inbounds ptr, ptr "
               << "@.pycnames, i64 " << i << "\n";
            o_ << "  store ptr " << val << ", ptr " << ptr << "\n";
        }
        for (std::size_t i = 0; i < kw_order_.size(); ++i) {
            need("declare ptr @pyc_rt_kwnames_from_csv(ptr)");
            std::string val = "%k" + std::to_string(i);
            std::string ptr = "%kp" + std::to_string(i);
            std::string ok = "kok" + std::to_string(i);
            std::string isnull = "%kn" + std::to_string(i);
            o_ << "  " << val << " = call ptr @pyc_rt_kwnames_from_csv(ptr "
               << cstr(kw_order_[i]) << ")\n";
            o_ << "  " << isnull << " = icmp eq ptr " << val << ", null\n";
            o_ << "  br i1 " << isnull << ", label %fail, label %" << ok << "\n";
            o_ << ok << ":\n";
            o_ << "  " << ptr << " = getelementptr inbounds ptr, ptr "
               << "@.kwnames, i64 " << i << "\n";
            o_ << "  store ptr " << val << ", ptr " << ptr << "\n";
        }
        o_ << "  ret i32 0\nfail:\n  ret i32 -1\n}\n";
    }

    void emit_declarations() {
        o_ << "\n";
        for (const std::string& d : decls_) o_ << d << "\n";
    }
