// Typed SSA IR -> textual LLVM IR (INTERFACES.md §3 -> §5).
//
// Deliberately a MECHANICAL translation. Every semantic decision was already
// made in lowering and is visible in the IR: ownership, error edges, which
// C-API symbol, which references are stolen. A4's directive says so
// explicitly -- if a program is wrong, that is A2/A3, and papering over it
// here would hide the defect from the layer that owns it.
//
// Text rather than the LLVM C++ API for now: it keeps pyc free of libLLVM
// linkage, and the output is readable, which matters while the backend is new.
#include <cstdint>
#include <cstdlib>
#include <cstring>
#include "pyc/ir/ir.hpp"
#include "pyc/rt/capi.hpp"

#include <map>
#include <optional>
#include <set>
#include <cctype>
#include <algorithm>
